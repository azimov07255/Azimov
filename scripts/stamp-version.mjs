#!/usr/bin/env node
/**
 * Stamps the build: hashes every file the app ships and writes
 *   version.json   (fetched by running apps to detect a new release; carries the "what's new" notes)
 *   js/version.js  (the hash baked into THIS copy of the app)
 * When a deployed version.json differs from the hash a running app was loaded with, the app offers an update.
 *
 *   node scripts/stamp-version.mjs          write both files
 *   node scripts/stamp-version.mjs --check  exit 1 if they are stale (handy in CI or a pre-commit hook)
 * Release notes come from the first entry of CHANGELOG.json (newest first).
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const INCLUDE = ['index.html', 'sw.js', 'manifest.webmanifest', 'apple-touch-icon.png', 'css', 'js', 'assets'];
const EXCLUDE = new Set(['js/version.js']);

function* walk(p) {
  const st = statSync(p);
  if (st.isDirectory()) for (const f of readdirSync(p).sort()) yield* walk(join(p, f));
  else yield p;
}
const h = createHash('sha256');
for (const entry of INCLUDE) {
  const p = join(ROOT, entry);
  if (!existsSync(p)) continue;
  for (const f of walk(p)) {
    const rel = relative(ROOT, f).split(sep).join('/');
    if (EXCLUDE.has(rel)) continue;
    h.update(rel + '\0');
    h.update(readFileSync(f));
    h.update('\0');
  }
}
const hash = h.digest('hex').slice(0, 12);
const log = JSON.parse(readFileSync(join(ROOT, 'CHANGELOG.json'), 'utf8'));
const cur = log[0];
const versionJson = JSON.stringify({ hash, version: cur.version, released: cur.date, notes: cur.notes, history: log.slice(0, 6) }, null, 2) + '\n';
const versionJs = `// GENERATED by scripts/stamp-version.mjs - do not edit.\nexport const APP_HASH = '${hash}';\nexport const APP_VERSION = '${cur.version}';\nexport const APP_DATE = '${cur.date}';\n`;

const files = [['version.json', versionJson], ['js/version.js', versionJs]];
if (process.argv.includes('--check')) {
  const stale = files.filter(([f, c]) => !existsSync(join(ROOT, f)) || readFileSync(join(ROOT, f), 'utf8') !== c);
  if (stale.length) {
    console.error('Stale:', stale.map((s) => s[0]).join(', '), '- run: node scripts/stamp-version.mjs');
    process.exit(1);
  }
  console.log('version stamp is current', hash);
} else {
  for (const [f, c] of files) writeFileSync(join(ROOT, f), c);
  console.log(`stamped v${cur.version} (${hash})`);
}
